"""Human-readable Markdown reporting for evaluation summaries."""

from pathlib import Path
from typing import Any


def _cell(value: Any) -> str:
    """Keep values safe and readable inside a Markdown table cell."""
    return str(value).replace("|", "\\|").replace("\r", " ").replace("\n", " ")


def render_markdown_report(summary: dict[str, Any]) -> str:
    """Render an evaluation summary as a readable Markdown report."""
    total = summary.get("total_tests", 0)
    passed = summary.get("passed_tests", 0)
    failed = summary.get("failed_tests", 0)
    pass_rate = summary.get("pass_rate", 0.0)
    threshold = summary.get("keyword_threshold", 0.0)
    details = summary.get("details", [])

    lines = [
        "# AI Output Evaluation Report",
        "",
        "> Rule-based baseline: checks expected keyword coverage and minimum output length.",
        "> It does not assess semantic correctness, factual accuracy, or safety.",
        "",
        "## Summary",
        "",
        "| Metric | Result |",
        "|:--|--:|",
        f"| Total test cases | {total} |",
        f"| Passed | {passed} |",
        f"| Failed | {failed} |",
        f"| Pass rate | {pass_rate:.1%} |",
        f"| Keyword threshold | {threshold:.1%} |",
        "",
        "## Test case results",
        "",
        "| Test ID | Status | Keyword coverage | Output length | Failed checks |",
        "|:--|:--:|--:|--:|:--|",
    ]

    for item in details:
        status = "PASS" if item.get("passed") else "FAIL"
        failures = ", ".join(item.get("failure_reasons", [])) or "—"
        lines.append(
            f"| {_cell(item.get('id', ''))} | {status} | "
            f"{item.get('keyword_coverage', 0.0):.1%} | "
            f"{item.get('output_length', 0)} | {_cell(failures)} |"
        )

    if not details:
        lines.append("| — | — | — | — | No test cases were provided |")

    for item in details:
        lines.extend([
            "",
            f"### {_cell(item.get('id', 'Test case'))} — "
            f"{'PASS' if item.get('passed') else 'FAIL'}",
            "",
            f"**Prompt:** {_cell(item.get('prompt', ''))}",
            "",
            f"- Matched keywords: {_cell(', '.join(item.get('matched_keywords', [])) or 'None')}",
            f"- Missing keywords: {_cell(', '.join(item.get('missing_keywords', [])) or 'None')}",
            f"- Duplicate expected keywords: {_cell(', '.join(item.get('duplicate_expected_keywords', [])) or 'None')}",
            f"- Minimum required length: {item.get('minimum_length', 0)} characters",
            f"- Actual normalized length: {item.get('output_length', 0)} characters",
            f"- Failed checks: {_cell(', '.join(item.get('failure_reasons', [])) or 'None')}",
        ])

    lines.extend(["", "---", "", "Generated by the AI Output Evaluator project.", ""])
    return "\n".join(lines)


def write_markdown_report(summary: dict[str, Any], output_path: str | Path) -> Path:
    """Write a Markdown report and return its path."""
    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_markdown_report(summary), encoding="utf-8")
    return path
