"""Interactive Streamlit dashboard for the rule-based output evaluator."""

import json
import tempfile
from pathlib import Path

import streamlit as st

from src.evaluator import LLMEvaluator

st.set_page_config(
    page_title="AI Output Evaluator Dashboard",
    page_icon="📊",
    layout="wide",
)

ROOT = Path(__file__).resolve().parent
DEFAULT_CASES = ROOT / "data" / "test_cases.json"


def evaluate_uploaded_cases(cases, threshold):
    """Evaluate uploaded test cases without keeping temporary files."""
    with tempfile.TemporaryDirectory() as temp_dir:
        input_path = Path(temp_dir) / "test_cases.json"
        input_path.write_text(json.dumps(cases, ensure_ascii=False), encoding="utf-8")
        evaluator = LLMEvaluator(input_path, keyword_threshold=threshold)
        details = [evaluator.evaluate_case(case) for case in evaluator.test_cases]

    total = len(details)
    passed = sum(item["passed"] for item in details)
    return {
        "evaluation_method": "rule_based_keyword_and_length_checks",
        "semantic_accuracy_assessed": False,
        "total_tests": total,
        "passed_tests": passed,
        "failed_tests": total - passed,
        "pass_rate": round(passed / total, 3) if total else 0.0,
        "keyword_threshold": threshold,
        "details": details,
    }


def validate_report(data):
    """Check the minimum structure needed by the dashboard."""
    required = {"total_tests", "passed_tests", "failed_tests", "pass_rate", "details"}
    if not isinstance(data, dict) or not required.issubset(data):
        raise ValueError("The JSON object is not a recognised evaluation report.")
    if not isinstance(data["details"], list):
        raise ValueError("The report 'details' field must be a list.")
    return data


st.title("AI Output Evaluator")
st.caption("Interactive quality dashboard · Rule-based baseline")

st.info(
    "This dashboard checks expected keyword coverage and minimum output length. "
    "It does not judge meaning, factual accuracy, context, or safety."
)

with st.sidebar:
    st.header("Dashboard settings")
    uploaded_file = st.file_uploader(
        "Upload test cases or an evaluation report (JSON)",
        type=["json"],
        help="Upload a test-case list or a report previously generated by this project.",
    )
    threshold = st.slider(
        "Keyword coverage threshold",
        min_value=0.0,
        max_value=1.0,
        value=0.8,
        step=0.05,
        help="Used when evaluating test cases. Existing reports keep their saved results.",
    )
    st.caption("Default data: data/test_cases.json")

try:
    if uploaded_file is None:
        if not DEFAULT_CASES.exists():
            st.error("Default test cases were not found. Upload a JSON file to continue.")
            st.stop()
        evaluator = LLMEvaluator(DEFAULT_CASES, keyword_threshold=threshold)
        details = [evaluator.evaluate_case(case) for case in evaluator.test_cases]
        total = len(details)
        passed = sum(item["passed"] for item in details)
        summary = {
            "total_tests": total,
            "passed_tests": passed,
            "failed_tests": total - passed,
            "pass_rate": round(passed / total, 3) if total else 0.0,
            "keyword_threshold": threshold,
            "details": details,
            "semantic_accuracy_assessed": False,
        }
        source_label = "Built-in sample test cases"
    else:
        uploaded_data = json.load(uploaded_file)
        if isinstance(uploaded_data, list):
            summary = evaluate_uploaded_cases(uploaded_data, threshold)
            source_label = "Uploaded test cases"
        else:
            summary = validate_report(uploaded_data)
            source_label = "Uploaded evaluation report"
except (OSError, ValueError, TypeError, json.JSONDecodeError) as exc:
    st.error(f"Could not load the data: {exc}")
    st.stop()

st.caption(f"Data source: {source_label}")

total = int(summary.get("total_tests", 0))
passed = int(summary.get("passed_tests", 0))
failed = int(summary.get("failed_tests", 0))
pass_rate = float(summary.get("pass_rate", 0.0))
details = summary.get("details", [])

metric_cols = st.columns(4)
metric_cols[0].metric("Total test cases", total)
metric_cols[1].metric("Passed", passed)
metric_cols[2].metric("Failed", failed)
metric_cols[3].metric("Pass rate", f"{pass_rate:.1%}")

st.progress(max(0.0, min(1.0, pass_rate)))
st.caption(f"Keyword threshold: {float(summary.get('keyword_threshold', threshold)):.0%}")

left, right = st.columns([1, 2])
with left:
    st.subheader("Outcome breakdown")
    st.bar_chart(
        [{"Status": "Passed", "Cases": passed}, {"Status": "Failed", "Cases": failed}],
        x="Status",
        y="Cases",
    )
with right:
    st.subheader("Test case results")
    table_rows = []
    for item in details:
        table_rows.append(
            {
                "Test ID": item.get("id", "—"),
                "Status": "PASS" if item.get("passed") else "FAIL",
                "Keyword coverage": f"{float(item.get('keyword_coverage', 0)):.1%}",
                "Output length": item.get("output_length", 0),
                "Failed checks": ", ".join(item.get("failure_reasons", [])) or "None",
            }
        )
    st.dataframe(table_rows, use_container_width=True, hide_index=True)

st.subheader("Test case details")
if not details:
    st.warning("No test cases are available in this dataset.")
for item in details:
    status = "PASS" if item.get("passed") else "FAIL"
    with st.expander(f"{status} · {item.get('id', 'Unnamed test case')}"):
        st.write("**Prompt**")
        st.write(item.get("prompt", "Not provided"))
        st.write("**Matched keywords**")
        st.write(", ".join(item.get("matched_keywords", [])) or "None")
        st.write("**Missing keywords**")
        st.write(", ".join(item.get("missing_keywords", [])) or "None")
        st.write("**Duplicate expected keywords**")
        st.write(", ".join(item.get("duplicate_expected_keywords", [])) or "None")
        st.write("**Checks**")
        checks = item.get("checks", {})
        if checks:
            st.json(checks)
        st.write("**Failure reasons**")
        st.write(", ".join(item.get("failure_reasons", [])) or "None")

st.divider()
st.caption(
    "Portfolio note: this is an explainable rule-based demonstration, not a production "
    "LLM evaluator or an automated assessment of semantic quality."
)
